/// Что уходит в правку расшифровки: слова человека, встроенные написания и
/// восстановленные названия. Порядок задаёт силу: пользовательская запись
/// перекрывает любую встроенную, написания — восстановления.
func dictationCorrections(user: [TranscriptCorrection],
                          includeBuiltInSpellings: Bool,
                          includeLatinTermRestorations: Bool) -> [TranscriptCorrection] {
    var result = normalizedTranscriptCorrections(user)
    var seen = Set(result.map { normalizedTranscriptCorrectionSource($0.source) })

    func append(_ entries: [TranscriptCorrection]) {
        for entry in entries {
            let key = normalizedTranscriptCorrectionSource(entry.source)
            guard !seen.contains(key) else { continue }
            seen.insert(key)
            result.append(entry)
        }
    }

    if includeBuiltInSpellings { append(BuiltInSpellings.all) }
    if includeLatinTermRestorations { append(LatinTermRestorations.all) }
    return result
}
